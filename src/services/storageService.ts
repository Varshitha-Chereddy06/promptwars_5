import { FullEventPlan, EventType, BudgetCategory, Milestone, Vendor } from '../types';
import { EVENT_TYPE_METADATA, DEFAULT_BUDGET_SPLITS, DEFAULT_TIMELINE_TEMPLATES, DEFAULT_VENDORS_BY_TYPE, PRESET_THEMES, INITIAL_GUESTS, INITIAL_TABLES } from '../constants/presets';
import { calculateDueDate, calculateAllocations } from './calculationService';

const STORAGE_KEY_PREFIX = 'soiree_event_plan_';
const API_KEY_STORAGE_KEY = 'soiree_gemini_api_key';

/**
 * Creates a brand new event plan for a given event type
 */
export function createInitialPlan(type: EventType): FullEventPlan {
  const meta = EVENT_TYPE_METADATA[type];
  
  // Default target date is 6 months from today for wedding, 2 months for birthday, 3 months for community
  const targetDate = new Date();
  const monthsAhead = type === 'wedding' ? 6 : type === 'birthday' ? 2 : 3;
  targetDate.setMonth(targetDate.getMonth() + monthsAhead);
  const dateStr = targetDate.toISOString().split('T')[0];

  const defaultCity = type === 'wedding' ? 'Charleston, SC' : type === 'birthday' ? 'Austin, TX' : 'Seattle, WA';
  const defaultTitle = type === 'wedding' ? 'Evelyn & Julian’s Wedding Celebration' :
                       type === 'birthday' ? 'Marcus’s 30th Studio 54 Birthday Bash' :
                       'Cascadia Green Maker & Arts Festival';
  const defaultHost = type === 'wedding' ? 'Evelyn Reed & Julian Vance' :
                      type === 'birthday' ? 'Marcus Vance' :
                      'Cascadia Community Arts Council';

  // Categories with calculated allocated amounts
  const rawCategories = DEFAULT_BUDGET_SPLITS[type].map((cat, idx) => ({
    ...cat,
    id: `cat-${type}-${idx + 1}`,
    allocatedAmount: Math.round((meta.defaultBudget * cat.percentage) / 100),
    spentAmount: 0
  }));

  // Log some initial spent amounts so user sees visual progress bars right away
  if (type === 'wedding') {
    rawCategories[0].spentAmount = 4500; // Venue deposit
    rawCategories[2].spentAmount = 1500; // Photo retainer
  } else if (type === 'birthday') {
    rawCategories[0].spentAmount = 1000; // Venue reservation
  } else {
    rawCategories[0].spentAmount = 1500; // Permit paid
  }

  // Milestones with calculated due dates
  const milestones: Milestone[] = DEFAULT_TIMELINE_TEMPLATES[type].map((m, idx) => ({
    id: `m-${type}-${idx + 1}`,
    title: m.title,
    daysBeforeEvent: m.daysBeforeEvent,
    calculatedDueDate: calculateDueDate(dateStr, m.daysBeforeEvent),
    category: m.category,
    status: idx === 0 ? 'completed' : idx === 1 ? 'in_progress' : 'pending',
    assignee: type === 'wedding' ? 'Evelyn' : type === 'birthday' ? 'Marcus' : 'Committee Lead',
    notes: m.notes
  }));

  // Vendors
  const vendors: Vendor[] = DEFAULT_VENDORS_BY_TYPE[type].map((v, idx) => ({
    id: `v-${type}-${idx + 1}`,
    category: v.category,
    name: v.name,
    contactName: 'Inquiry Specialist',
    email: `contact@${v.name.toLowerCase().replace(/[^a-z]/g, '')}.com`,
    phone: '+1 (555) 019-2831',
    status: idx === 0 ? 'hired' : idx === 1 ? 'quote_received' : 'researching',
    quotedAmount: v.estimatedPrice,
    depositPaid: idx === 0 ? Math.round(v.estimatedPrice * 0.4) : 0,
    rating: 5,
    notes: v.notes
  }));

  const activeTheme = type === 'wedding' ? PRESET_THEMES[0] : type === 'birthday' ? PRESET_THEMES[2] : PRESET_THEMES[3];

  return {
    details: {
      id: `event-${type}-${Date.now()}`,
      type,
      title: defaultTitle,
      hostNames: defaultHost,
      date: dateStr,
      time: '17:00',
      city: defaultCity,
      venueName: type === 'wedding' ? 'Magnolia Estate' : type === 'birthday' ? 'The Violet Crown Rooftop' : 'Green Lake Community Park',
      vibe: meta.defaultVibe,
      totalBudget: meta.defaultBudget,
      guestCount: meta.defaultGuestCount,
      currency: 'USD',
      notes: 'Initial event plan generated by Soirée AI Assistant.',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    },
    categories: rawCategories,
    expenses: [
      {
        id: 'exp-1',
        categoryId: rawCategories[0].id,
        name: `${rawCategories[0].name} - Deposit`,
        amount: rawCategories[0].spentAmount,
        date: new Date().toISOString().split('T')[0],
        paidTo: vendors[0]?.name || 'Primary Venue'
      }
    ],
    milestones,
    vendors,
    guests: INITIAL_GUESTS,
    tables: INITIAL_TABLES,
    activeTheme,
    aiSavedOutputs: {},
    chatHistory: [
      {
        id: 'msg-welcome',
        sender: 'assistant',
        content: `👋 Welcome to Soirée! I have initialized your **${meta.name}** plan for **${defaultCity}** with a $${meta.defaultBudget.toLocaleString()} budget and ${meta.defaultGuestCount} guests.\n\nAsk me anything: brainstorm themes, audit your budget, craft speeches, or test contingency plans!`,
        timestamp: new Date().toISOString()
      }
    ]
  };
}

/**
 * Loads plan from localStorage or creates default
 */
export function loadPlan(type: EventType): FullEventPlan {
  try {
    const raw = localStorage.getItem(`${STORAGE_KEY_PREFIX}${type}`);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && parsed.details && parsed.details.type === type) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn(`Failed to parse saved plan for ${type}`, err);
  }
  return createInitialPlan(type);
}

/**
 * Saves plan to localStorage
 */
export function savePlan(plan: FullEventPlan): void {
  try {
    plan.details.updatedAt = new Date().toISOString();
    localStorage.setItem(`${STORAGE_KEY_PREFIX}${plan.details.type}`, JSON.stringify(plan));
  } catch (err) {
    console.error('Failed to save plan to localStorage', err);
  }
}

/**
 * Encodes plan into a shareable URL hash
 */
export function generateShareableUrl(plan: FullEventPlan): string {
  try {
    const minified = {
      d: plan.details,
      c: plan.categories,
      m: plan.milestones,
      v: plan.vendors,
      t: plan.activeTheme?.id
    };
    const jsonStr = JSON.stringify(minified);
    const base64 = btoa(encodeURIComponent(jsonStr));
    const url = new URL(window.location.href);
    url.hash = `plan=${base64}`;
    return url.toString();
  } catch {
    return window.location.href;
  }
}

/**
 * Checks and decodes shared plan from URL hash if available
 */
export function decodeSharedPlanFromUrl(): FullEventPlan | null {
  try {
    const hash = window.location.hash;
    if (hash.startsWith('#plan=')) {
      const b64 = hash.replace('#plan=', '');
      const jsonStr = decodeURIComponent(atob(b64));
      const minified = JSON.parse(jsonStr);
      if (minified && minified.d && minified.d.type) {
        const full = createInitialPlan(minified.d.type);
        full.details = { ...full.details, ...minified.d };
        if (minified.c) full.categories = minified.c;
        if (minified.m) full.milestones = minified.m;
        if (minified.v) full.vendors = minified.v;
        return full;
      }
    }
  } catch (e) {
    console.warn('Could not decode plan from URL hash', e);
  }
  return null;
}

/**
 * Exports plan as downloadable .soiree.json
 */
export function exportPlanAsJSON(plan: FullEventPlan): void {
  const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(plan, null, 2));
  const downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute('href', dataStr);
  const cleanTitle = plan.details.title.toLowerCase().replace(/[^a-z0-9]/g, '_');
  downloadAnchor.setAttribute('download', `${cleanTitle}_soiree_plan.json`);
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
}

/**
 * Stored API Key management
 */
export function getStoredApiKey(): string {
  try {
    return localStorage.getItem(API_KEY_STORAGE_KEY) || '';
  } catch {
    return '';
  }
}

export function setStoredApiKey(key: string): void {
  try {
    if (!key) {
      localStorage.removeItem(API_KEY_STORAGE_KEY);
    } else {
      localStorage.setItem(API_KEY_STORAGE_KEY, key.trim());
    }
  } catch (e) {
    console.error('Failed to persist API key', e);
  }
}
